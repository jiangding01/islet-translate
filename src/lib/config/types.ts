import type { LanguageCode } from '@/lib/languages';

// Pure types and constants: safe to import from any context (no zod).

export const THEMES = ['system', 'light', 'dark'] as const;
export type Theme = (typeof THEMES)[number];

/** How a translation is set apart from the original on pages (M2). */
export const PAGE_STYLES = ['plain', 'faded', 'underline', 'highlight'] as const;
export type PageStyle = (typeof PAGE_STYLES)[number];

/** What a new page-translation session shows first. */
export const PAGE_MODES = ['bilingual', 'translation'] as const;
export type PageMode = (typeof PAGE_MODES)[number];

/** Where the page-translation isle docks on the viewport edge (M2b). */
export const ISLE_DOCKS = ['right', 'left', 'bottom'] as const;
export type IsleDock = (typeof ISLE_DOCKS)[number];

/** The modifier held over a paragraph to toggle it (M3b), or `off`. No Shift: see the plan. */
export const HOLD_KEYS = ['ctrl', 'alt', 'off'] as const;
export type HoldKey = (typeof HOLD_KEYS)[number];

export const BUILTIN_ENGINES = ['google', 'openai', 'deepseek', 'gemini'] as const;
export type BuiltinEngine = (typeof BUILTIN_ENGINES)[number];

/** Generated by the settings page: `custom-` + 8 lowercase letters or digits. */
export type CustomProviderId = `custom-${string}`;
export const CUSTOM_PROVIDER_ID_PATTERN = /^custom-[a-z0-9]{8}$/;
export const MAX_CUSTOM_PROVIDERS = 10;
export const CUSTOM_PROVIDER_LIMITS = {
  name: 40,
  baseURL: 2048,
  model: 200,
  extraBody: 2000,
} as const;

/** A built-in engine, or the id of a custom OpenAI-compatible provider. */
export type Engine = BuiltinEngine | CustomProviderId;

/** Cooldown and cache scope: every custom provider belongs to the `custom` family. */
export type EngineFamily = BuiltinEngine | 'custom';

export interface CustomProvider {
  name: string;
  baseURL: string;
  model: string;
  /** Extra request body fields: JSON object text as typed (src/lib/config/extra-body.ts). */
  extraBody?: string;
}

export function isBuiltinEngine(value: unknown): value is BuiltinEngine {
  return typeof value === 'string' && (BUILTIN_ENGINES as readonly string[]).includes(value);
}

export function isCustomProviderId(value: unknown): value is CustomProviderId {
  return typeof value === 'string' && CUSTOM_PROVIDER_ID_PATTERN.test(value);
}

/** Syntactically valid engine value (a custom id may still be dangling). */
export function isEngineId(value: unknown): value is Engine {
  return isBuiltinEngine(value) || isCustomProviderId(value);
}

export function engineFamily(engine: Engine): EngineFamily {
  return isBuiltinEngine(engine) ? engine : 'custom';
}

export const CONFIG_SCHEMA_VERSION = 1;
export const CONFIG_STORAGE_KEY = 'config';

export interface ConfigV1 {
  ui: { theme: Theme };
  language: { target: LanguageCode; source: 'auto' | LanguageCode };
  translation: { engine: Engine };
  page: { style: PageStyle; mode: PageMode; isleDock: IsleDock; holdKey: HoldKey };
  /** Selection translation (M3a): the dot shown after selecting foreign text. */
  selection: { showDot: boolean };
  /**
   * `thinking`: the thinking mode, off by default to keep translations fast; it only takes
   * effect where the rule table knows the model (src/lib/config/thinking-rules.ts).
   * `extraBody`: extra request body fields, as for custom providers.
   */
  providers: {
    openai: { baseURL: string; model: string; thinking: boolean; extraBody: string };
    deepseek: { model: string; thinking: boolean };
    gemini: { model: string; thinking: boolean };
  };
  /** Insertion order is display order. Keys are CustomProviderId (validated at runtime). */
  customProviders: Record<string, CustomProvider>;
}

export interface ConfigSnapshot {
  schemaVersion: typeof CONFIG_SCHEMA_VERSION;
  data: ConfigV1;
}

type Primitive = string | number | boolean | bigint | symbol | null | undefined;

/** Paths stop at leaves, arrays and records: those are replaced as a whole. */
type StopsHere<T> = T extends Primitive
  ? true
  : T extends readonly unknown[]
    ? true
    : string extends keyof T
      ? true
      : false;

export type DotPath<T, Prefix extends string = ''> = {
  [K in keyof T & string]: StopsHere<NonNullable<T[K]>> extends true
    ? `${Prefix}${K}`
    : DotPath<NonNullable<T[K]>, `${Prefix}${K}.`>;
}[keyof T & string];

export type PathValue<T, P extends string> = P extends `${infer Head}.${infer Rest}`
  ? Head extends keyof T
    ? PathValue<T[Head], Rest>
    : never
  : P extends keyof T
    ? T[P]
    : never;

export type ConfigPath = DotPath<ConfigV1>;

/** `customProviders` is never replaced as a whole: see CustomProviderChange. */
type PlainPath = Exclude<ConfigPath, 'customProviders'>;

/**
 * One custom provider at a time, so two pages editing different providers never
 * overwrite each other. `update` merges only the given fields, so two quick
 * edits of one provider keep both, and it fails for a provider that is gone
 * instead of bringing it back.
 */
export type CustomProviderChange =
  | { path: 'customProviders'; key: CustomProviderId; add: CustomProvider }
  | { path: 'customProviders'; key: CustomProviderId; update: Partial<CustomProvider> }
  | { path: 'customProviders'; key: CustomProviderId; remove: true };

export type ConfigChange =
  | {
      [P in PlainPath]: { path: P; value: PathValue<ConfigV1, P> };
    }[PlainPath]
  | CustomProviderChange;
